/**
 * ============================================================================
 *  joystick.h —— 摇杆分区（把摇杆的原始坐标翻译成"往哪走"）
 * ============================================================================
 *
 *  【PS2 摇杆原始数据】
 *  每个轴报一个 0~255 的数，手松开时是 128（正中间）：
 *
 *      Y 轴：推到顶 = 0      中间 = 128      推到底 = 255
 *      X 轴：推到左 = 0      中间 = 128      推到右 = 255
 *
 *  注意 Y 轴是【反的】：往上推数字反而变小。
 *  所以代码里所有 Y 轴都要先"翻个跟头"才能用。
 *
 *  【本模块干什么】
 *  把 (原始x, 原始y) 变成一个"方向区 + 推了多少"，
 *  外面就不用自己去跟 0~255 这堆原始数字打交道了。
 *
 *  【左摇杆分区图】（8 分区模式，从上往下看）
 *
 *            左上      上      右上
 *               NW ─── N ─── NE
 *                │           │
 *           左   W   中心    E   右
 *                │           │
 *               SW ─── S ─── SE
 *            左下      下      右下
 *
 *  【右摇杆分区图】
 *              左  ←── 中心 ──→  右
 *                   停转   顺时针
 *                   逆时针
 * ============================================================================
 */
#ifndef __JOYSTICK_H
#define __JOYSTICK_H

#include <stdint.h>
#include "robot_conf.h"

/**
 * 左摇杆的 9 个分区。
 * 用枚举（enum）而不是写 0~8，是为了让代码里能看懂：
 * 看到 JOY_N 就知道是"往北"，看到 3 就啥也不知道。
 */
typedef enum
{
    JOY_CENTER = 0,     /* 在中间（手没碰，或者碰得很轻） */
    JOY_N,              /* 上   → 前进 */
    JOY_NE,             /* 右上 → 右前方 45° 斜行 */
    JOY_E,              /* 右   → 右平移 */
    JOY_SE,             /* 右下 → 右后方 45° 斜行 */
    JOY_S,              /* 下   → 后退 */
    JOY_SW,             /* 左下 → 左后方 45° 斜行 */
    JOY_W,              /* 左   → 左平移 */
    JOY_NW              /* 左上 → 左前方 45° 斜行 */
} JoyDir;

/**
 * 左摇杆读出来的结果：往哪个区 + 推了多少（0~100）
 */
typedef struct
{
    JoyDir  dir;
    uint8_t mag;
} JoyResult;

/* ---------------------------------------------------------------------------
 *  对外函数
 * ------------------------------------------------------------------------- */

/**
 * 读左摇杆，返回"往哪个区 + 推了多少"。
 * raw_x / raw_y 直接传手柄报上来的 0~255 原始值。
 */
JoyResult Joystick_ReadMove(uint8_t raw_x, uint8_t raw_y);

/**
 * 把分区结果换算成运动分量。
 * vx = 前后（+ 前进），vy = 平移（+ 右移）。
 */
void Joystick_ToVector(JoyResult r, int16_t *vx, int16_t *vy);

/**
 * 读右摇杆，返回旋转速度。
 * 返回 +100~+1 = 顺时针，-100~-1 = 逆时针，0 = 不转。
 */
int16_t Joystick_ReadRotate(uint8_t raw_x);

#endif /* __JOYSTICK_H */
