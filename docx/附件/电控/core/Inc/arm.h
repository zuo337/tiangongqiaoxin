/**
 * ============================================================================
 *  arm.h —— 机械臂按键处理（8 个按键 → 4 个舵机）
 * ============================================================================
 *
 *  【按键布局】十字键 4 个 + 面板 4 个，一共 8 个，全部归舵机。
 *  底盘完全交给两个摇杆（见 ctrl.c），这里一个键都不占。
 *
 *  【映射关系】
 *
 *    十字键 ↑    → 小舵机6  顺时针
 *    十字键 ↓    → 小舵机6  逆时针
 *    十字键 ←    → 大舵机1  顺时针
 *    十字键 →    → 大舵机1  逆时针
 *
 *    △ 三角      → 大舵机2  顺时针
 *    × 叉        → 大舵机2  逆时针
 *    □ 方块      → 大舵机3  顺时针
 *    ○ 圆圈      → 大舵机3  逆时针
 *
 *  注意"顺时针"指的是这个键让脉宽变大。舵机装反了就把
 *  arm.c 表里那一行的 +1 / -1 对调，不要来这里动。
 *
 *  【唯一锁存】
 *  同一时刻只响应一个舵机：谁先按下谁占用，别的键一律无视，
 *  直到这个键松开。这样十字键斜着按（同时触发 ↑ 和 ←）也不会
 *  两个舵机一起转。
 * ============================================================================
 */
#ifndef __ARM_H
#define __ARM_H

#include <stdint.h>
#include "servo.h"

/**
 * 每轮主循环调一次。
 *
 * @param btn1 手柄报上来的第一组按键字节（注意：位 = 0 表示按下）
 * @param btn2 第二组按键字节
 *
 * 行为：
 *   按住的键 → 对应舵机每调一次走一步（SERVO_STEP_US 微秒）
 *   没按的键 → 什么都不做，舵机保持在当前位置
 *
 * 为什么"没按也不动"是对的：
 *   舵机的脉冲只要还在继续发（定时器一直跑），它就会一直用力
 *   顶在那个角度上。所以软件不需要做任何"保持"动作。
 */
void Arm_HandleKeys(uint8_t btn1, uint8_t btn2);

#endif /* __ARM_H */
