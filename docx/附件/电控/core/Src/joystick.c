/**
 * ============================================================================
 *  joystick.c —— 摇杆分区
 * ============================================================================
 */
#include "joystick.h"

/* ==========================================================================
 *  内部函数：把 0~255 的原始值翻成 -100 ~ +100
 *
 *  为什么是 127 而不是 128？
 *    上半段：128 → 100（推到顶 0 时是 +100）
 *    下半段：127 → -100（推到底 255 时是 -100）
 *    因为 255-128 = 127，而 0-128 = -128，两边不对称。
 *    用它俩各自的最大值做分母，正反两个方向才能都正好到 100。
 * ========================================================================== */
static int16_t Joy_Norm(uint8_t raw)
{
    int16_t v = (int16_t)raw - 128;

    if (v >= 0) return (int16_t)((int32_t)v * 100 / 127);
    else        return (int16_t)((int32_t)v * 100 / 128);
}


/* ==========================================================================
 *  内部函数：判断落在哪个 45° 扇区
 *
 *  ── 为什么不用 atan2 算角度？──
 *  STM32F103 是 Cortex-M3，【没有硬件浮点单元】，
 *  调一次 atan2 + 除法要花掉几千个时钟周期，20ms 一次的循环里根本扛不住。
 *  所以这里用一个纯整数的比较技巧，几十个周期就完事。
 *
 *  ── 技巧原理 ──
 *  8 个扇区的分界线在 22.5°、67.5°、112.5°……
 *  数学上 tan(22.5°) = 0.4142，我们取个好算的近似值 0.4 = 2/5。
 *
 *    判断"横向为主"：|y| < 0.4 × |x|   →  写成整数式  |y| × 5 < |x| × 2
 *    判断"纵向为主"：|x| < 0.4 × |y|   →  写成整数式  |x| × 5 < |y| × 2
 *    两个都不满足   ：就在 45° 斜角的扇区里
 *
 *  举例：往右上推，x=100 y=30（约 17°）
 *    |y|×5 = 150 ， |x|×2 = 200  →  150 < 200 成立 → 判成"右"
 *  往右上推，x=100 y=100（正好 45°）
 *    |y|×5 = 500 ， |x|×2 = 200  →  不成立
 *    |x|×5 = 500 ， |y|×2 = 200  →  不成立
 *    → 两个都不满足 → 判成"右上"
 * ========================================================================== */
static JoyDir Joy_Classify(int16_t nx, int16_t ny)
{
    int16_t ax = nx, ay = ny;

    /* 先取绝对值。注意 (nx<0) ? -nx : nx 的写法，
     * 不要写 abs(nx)，abs 对最小负数 -32768 会出问题，而且是库函数。*/
    if (ax < 0) ax = (int16_t)(-ax);
    if (ay < 0) ay = (int16_t)(-ay);

#if JOY_USE_DIAGONAL
    /* ── 8 分区模式 ── */
    if ((int32_t)ay * 5 < (int32_t)ax * 2)
    {
        /* 横向占主导 → 右 或 左 */
        return (nx > 0) ? JOY_E : JOY_W;
    }
    if ((int32_t)ax * 5 < (int32_t)ay * 2)
    {
        /* 纵向占主导 → 上 或 下 */
        return (ny > 0) ? JOY_N : JOY_S;
    }
    /* 剩下的是四个斜角 */
    if (nx > 0) return (ny > 0) ? JOY_NE : JOY_SE;
    else        return (ny > 0) ? JOY_NW : JOY_SW;
#else
    /* ── 4 分区模式：简单比一下 x 和 y 谁大就行 ── */
    if (ax > ay)
    {
        return (nx > 0) ? JOY_E : JOY_W;
    }
    else
    {
        return (ny > 0) ? JOY_N : JOY_S;
    }
#endif
}


/* ==========================================================================
 *  对外：读左摇杆
 * ========================================================================== */
JoyResult Joystick_ReadMove(uint8_t raw_x, uint8_t raw_y)
{
    JoyResult r;
    int16_t nx, ny;
    int16_t ax, ay;

    /* ① 翻成 -100 ~ +100。
     *    Y 轴要反号：手柄往上推原值变小，但我们希望"上"是正数。*/
    nx = Joy_Norm(raw_x);
    ny = (int16_t)(-Joy_Norm(raw_y));

    /* ② 死区判定
     *
     * 这里用 max(|x|, |y|) 作为"推了多少"（学名叫切比雪夫距离）。
     * 好处是不用开根号，F1 上算得飞快。
     * 缺点是把圆形的摇杆行程映射成了一个正方形，
     * 不过对手感几乎没影响，还能保证推到角落也满速。
     */
    ax = (nx >= 0) ? nx : (int16_t)(-nx);
    ay = (ny >= 0) ? ny : (int16_t)(-ny);

    if (ax < JOY_DEADZONE && ay < JOY_DEADZONE)
    {
        /* 手没碰，或者碰得很轻 → 当成中间，车保持滑停 */
        r.dir = JOY_CENTER;
        r.mag = 0;
        return r;
    }

    /* ③ 判断落在哪个扇区 */
    r.dir = Joy_Classify(nx, ny);

    /* ④ 推的幅度 = x 和 y 里比较大的那个 */
    r.mag = (uint8_t)((ax > ay) ? ax : ay);

    return r;
}


/* ==========================================================================
 *  对外：把分区结果换算成 vx / vy
 * ========================================================================== */
void Joystick_ToVector(JoyResult r, int16_t *vx, int16_t *vy)
{
    int16_t m = (int16_t)r.mag;

    /* 斜向时 x、y 各分一半。
     *
     * 为什么是 0.707 而不是 0.5？
     *   45° 斜行时，车身速度 v 分解到前后、左右两个轴上，
     *   每个轴是 v × cos(45°) = v × 0.707。
     *   如果直接给 0.5，斜着走就会比直着走慢一截，手感对不上。
     *   707 就是 0.707 放大一千倍取整，避免用浮点。
     */
    int16_t d = (int16_t)((int32_t)m * 707 / 1000);

    switch (r.dir)
    {
        case JOY_N:  *vx =  m; *vy =  0; break;
        case JOY_S:  *vx = -m; *vy =  0; break;
        case JOY_E:  *vx =  0; *vy =  m; break;
        case JOY_W:  *vx =  0; *vy = -m; break;

        case JOY_NE: *vx =  d; *vy =  d; break;
        case JOY_NW: *vx =  d; *vy = -d; break;
        case JOY_SE: *vx = -d; *vy =  d; break;
        case JOY_SW: *vx = -d; *vy = -d; break;

        default:     *vx =  0; *vy =  0; break;   /* 中间 → 不动 */
    }
}


/* ==========================================================================
 *  对外：读右摇杆，得到旋转速度
 *  右摇杆只用左右方向，上下不管。
 * ========================================================================== */
int16_t Joystick_ReadRotate(uint8_t raw_x)
{
    int16_t nx = Joy_Norm(raw_x);

    /* 死区：在中间就别转，不然手一抖车就原地扭 */
    if (nx > -JOY_DEADZONE && nx < JOY_DEADZONE)
    {
        return 0;
    }

    /* 往右推 = 顺时针（正），往左推 = 逆时针（负） */
    return nx;
}
