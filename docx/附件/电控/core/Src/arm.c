/**
 * ============================================================================
 *  arm.c —— 机械臂按键处理（8 个按键 → 4 个舵机）
 * ============================================================================
 *
 *  本文件只负责三件事：
 *    ① 一张对照表：哪个键 → 哪路舵机 → 朝哪转
 *    ② 边沿检测：只认"刚按下去"那一下，不认"一直按着"
 *    ③ 唯一锁存：同一时刻只让一个键生效
 *
 *  脉宽怎么算、往哪个寄存器写，一概不管 —— 那是 servo.c 的事。
 * ============================================================================
 */
#include "arm.h"
#include "ps2.h"        /* PS2_IS_PRESSED 宏、各按键位掩码 */
#include "servo.h"


/* ---------------------------------------------------------------------------
 *  一、键位对照表 —— 想换键、换方向、换舵机，只改这张表
 *
 *  grp 字段是干嘛的？
 *    PS2 把按键分成两个字节上报，两个字节里都有 0x10、0x40 这些
 *    重复的位值。光看掩码分不出是"十字键上"还是"三角"。
 *    所以要额外记一个"这个键在第几组字节里"。
 *      grp = 0 → btn1（十字键、SELECT、START、L3、R3）
 *      grp = 1 → btn2（△○×□、L1/L2/R1/R2）
 *
 *  dir 字段：
 *    +1 → 脉宽变大（舵机朝一个方向转）
 *    -1 → 脉宽变小（反方向）
 *
 *  装车后发现某个键转向反了？
 *    把那一行的 +1 改成 -1（或反过来），别去改 servo.c 的符号，
 *    也别去改接线。
 * ------------------------------------------------------------------------- */
typedef struct
{
    uint8_t grp;      /* 0 = btn1, 1 = btn2 */
    uint8_t mask;     /* 键位掩码 */
    uint8_t id;       /* 舵机逻辑编号（1/2/3/6，不是数组下标） */
    int8_t  dir;      /* +1 / -1 */
} Arm_KeyMap;

#define ARM_KEY_COUNT   8u

static const Arm_KeyMap s_map[ARM_KEY_COUNT] =
{
    /* ── 左手：十字键 → 大舵机1 + 小舵机6 ───────────────────────── */
    { 0u, PS2_BTN1_UP,    SERVO_ID_SMALL6, +1 },   /* ↑  小舵机6 顺时针 */
    { 0u, PS2_BTN1_DOWN,  SERVO_ID_SMALL6, -1 },   /* ↓  小舵机6 逆时针 */
    { 0u, PS2_BTN1_LEFT,  SERVO_ID_BIG1,   +1 },   /* ←  大舵机1 顺时针 */
    { 0u, PS2_BTN1_RIGHT, SERVO_ID_BIG1,   -1 },   /* →  大舵机1 逆时针 */

    /* ── 右手：面板四键 → 大舵机2 + 大舵机3 ─────────────────────── */
    { 1u, PS2_BTN2_TRIANGLE, SERVO_ID_BIG2, +1 },  /* △  大舵机2 顺时针 */
    { 1u, PS2_BTN2_CROSS,    SERVO_ID_BIG2, -1 },  /* ×  大舵机2 逆时针 */
    { 1u, PS2_BTN2_SQUARE,   SERVO_ID_BIG3, +1 },  /* □  大舵机3 顺时针 */
    { 1u, PS2_BTN2_CIRCLE,   SERVO_ID_BIG3, -1 },  /* ○  大舵机3 逆时针 */
};


/* ---------------------------------------------------------------------------
 *  二、锁存状态
 *
 *  s_prev_down ：上一拍的按键状态，第 i 位对应 s_map 的第 i 行，1 = 按着。
 *                 用它算"刚按下"的边沿，否则按住不动会每拍都算新按下。
 *
 *  s_active    ：当前锁在哪一行，-1 = 空闲。
 * ------------------------------------------------------------------------- */
static uint8_t s_prev_down = 0u;
static int8_t  s_active    = -1;


/* ---------------------------------------------------------------------------
 *  三、内部工具：在一堆被按下的键里挑一个
 *
 *  为什么规定"挑最低位"？
 *    同时按下两个键的时候，总得选一个。挑最低位是为了让结果确定 ——
 *    同样的按键组合，每次选中的都一样。如果随便挑，你会看到
 *    "有时动这个、有时动那个"，然后开始怀疑人生。
 * ------------------------------------------------------------------------- */
static int8_t pick_first(uint8_t bits)
{
    uint8_t i;

    for (i = 0u; i < ARM_KEY_COUNT; i++)
    {
        if ((bits & (uint8_t)(1u << i)) != 0u)
        {
            return (int8_t)i;
        }
    }
    return -1;
}


/* ---------------------------------------------------------------------------
 *  四、对外：处理 8 个按键
 * ------------------------------------------------------------------------- */
void Arm_HandleKeys(uint8_t btn1, uint8_t btn2)
{
    uint8_t down = 0u;      /* 这一拍哪些行被按着（位图） */
    uint8_t fresh;          /* 这一拍"刚按下"的行 */
    uint8_t i;
    int8_t  row;

    /* ── 4.1 把两个按键字节翻译成行位图 ──
     *
     * 这里必须用 PS2_IS_PRESSED 宏，不能直接写 & 判断。
     * 因为 PS2 协议里【按下 = 0】，没按才是 1。
     * 直接写 if (btn1 & mask) 会得到完全相反的结果 ——
     * 症状是"松开手的时候舵机猛转"，而你会去查舵机代码。
     * 宏的定义是 ((byte & bitmask) == 0u)，已经把这个反逻辑包好了。 */
    for (i = 0u; i < ARM_KEY_COUNT; i++)
    {
        uint8_t byte_now = (s_map[i].grp == 0u) ? btn1 : btn2;

        if (PS2_IS_PRESSED(byte_now, s_map[i].mask))
        {
            down |= (uint8_t)(1u << i);
        }
    }

    /* ── 4.2 算边沿：这一拍按着、上一拍没按着 = 刚按下 ── */
    fresh = (uint8_t)(down & (uint8_t)(~s_prev_down));

    if (s_active < 0)
    {
        /* ── 4.3 空闲：等第一个新按下的键，抢到锁 ── */
        if (fresh != 0u)
        {
            row = pick_first(fresh);
            if (row >= 0)
            {
                s_active = row;
                Servo_Step(s_map[row].id, s_map[row].dir);   /* 按下立刻走一步 */
            }
        }
        /* 这一拍只处理一个键。同时按下两个的话，另一个直接忽略 ——
         * 这就是"唯一锁存"的字面意思。 */
    }
    else
    {
        /* ── 4.4 已经被某一行锁住 ── */
        if ((down & (uint8_t)(1u << s_active)) != 0u)
        {
            /* 锁住的那个键还按着 → 继续走。
             * 主循环 20ms 一次，所以是每 20ms 走一步，走起来很顺。 */
            Servo_Step(s_map[s_active].id, s_map[s_active].dir);

            /* 按着它的同时去按别的键 → 什么都不做，直接无视。
             * 注意：这里【不能】改成"别的键也能动"。一旦允许，
             * 十字键斜按就会让两个舵机同时转。 */
        }
        else
        {
            /* ── 4.5 锁住的那个键松开了 → 释放锁 ── */
            s_active = -1;

            /* 交接：如果松手时手里还按着别的键，把锁交给它。
             *
             * 为什么要有交接？
             *   没有的话，你按住 ↑（小6 在转），顺手按住 ←，然后
             *   松开 ↑ —— 这时 ← 明明还按着，却永远不动了，
             *   必须松手重按。手感会像卡住一样。
             *
             * 交接时也只走一步，和"新按下"一致，不会突然连发。 */
            if (down != 0u)
            {
                row = pick_first(down);
                if (row >= 0)
                {
                    s_active = row;
                    Servo_Step(s_map[row].id, s_map[row].dir);
                }
            }
        }
    }

    /* ── 4.6 记下这一拍，供下一拍算边沿 ── */
    s_prev_down = down;
}
