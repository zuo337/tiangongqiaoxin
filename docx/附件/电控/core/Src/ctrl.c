/**
 * ============================================================================
 *  ctrl.c —— 总调度
 *
 *  整个机器人的"心跳"就在这个文件的 CTRL_Update() 里。
 * ============================================================================
 *
 *  【手柄分工】
 *
 *    左摇杆         → 底盘前后左右平移（模拟量，推多少走多快）
 *    右摇杆左右     → 底盘原地转（顺时针 / 逆时针）
 *
 *    十字键 ↑ ↓     → 小舵机6  顺时针 / 逆时针
 *    十字键 ← →     → 大舵机1  顺时针 / 逆时针
 *    △  ×          → 大舵机2  顺时针 / 逆时针
 *    □  ○          → 大舵机3  顺时针 / 逆时针
 *
 *    L1 / R1        → 底盘原地转的【按键备份】（右摇杆失灵时用）
 *    L2 R2 SELECT START → 空着，留给急停、存位、回位这些功能
 *
 *  【为什么底盘只给摇杆，按键全给舵机】
 *
 *    一个拇指管一边，这是手柄的物理事实：
 *      左拇指在十字键和左摇杆之间只能选一个；
 *      右拇指在面板键和右摇杆之间只能选一个。
 *
 *    所以"一边开车一边顺手按四个舵机键"物理上做不到。
 *    本方案的选择是：开车用摇杆，要调舵机就先把摇杆松开让车停下。
 *    比赛时抓运动中的方块，靠两个拇指同时推摇杆 + 舵机键已经
 *    预调到工作位，不需要中途去按。
 *
 *  【为什么没有"按舵机键就强制停车"的互锁】
 *
 *    讨论过，明确不要。因为比赛要抓运动的方块，需要在车移动的
 *    同时微调机构。加了互锁就做不到了。
 *
 *    代价是：手去按舵机键的时候，摇杆别碰。车会按摇杆的输入继续走。
 *    这是操作纪律，不是代码能替你保证的事。
 * ============================================================================
 */
#include "ctrl.h"
#include "robot_conf.h"
#include "main.h"       /* HAL_GetTick：数字模式自动重试要用到系统时基 */
#include "ps2.h"        /* 你原有的：PS2_Init / PS2_ReadData / PS2_GetData */
#include "drv8833.h"    /* 你原有的：DRV8833_Init */
#include "mecanum.h"
#include "joystick.h"
#include "arm.h"


/* ==========================================================================
 *  L1 / R1 备用转向的速度（%）
 *
 *  按键是开关量，只能给一个固定速度。60 = 六成速，好控。
 *  这个值只在右摇杆转向失灵的时候才会用到，正常操作碰不到它。
 * ========================================================================== */
#define BTN_DRIVE_SPEED   60


/* ==========================================================================
 *  对外：初始化
 * ========================================================================== */
void CTRL_Init(void)
{
    /* 顺序有讲究：先让电机断电，再让舵机回中，最后去握手柄。
     *
     * 这样上电瞬间车不会乱冲。舵机还是会回中位（1500），
     * 这是无法避免的 —— 舵机通电就必须有脉冲，有脉冲就必然有角度。
     * 所以装机构时一定要先想清楚"中位会不会撞到东西"。 */
    DRV8833_Init();     /* 你原有：启动 TIM2/TIM3 八路 PWM 并先让车停住 */
    Servo_Init();       /* 启动 TIM4_CH1~3 + TIM1_CH4，四路舵机回中位 */
    PS2_Init();         /* 你原有：手柄初始化 + 进模拟模式 */
}


/* ==========================================================================
 *  对外：主循环每次都调这个
 * ========================================================================== */
void CTRL_Update(void)
{
    PS2_Data d;
    int16_t vx = 0, vy = 0, w = 0;

    /* ──────────────────────────────────────────────────────────────
     *  ① 读手柄
     *
     * PS2_ReadData() 返回 0 表示"这一帧没收到 0x5A"，
     * 也就是手柄没开、没配对、或者中途断了。
     * 这时候数据全是随机数，绝对不能拿去驱动电机 —— 车会失控乱冲。
     * 所以直接停车然后返回，这一轮什么都不做。
     *
     * 舵机不用管：定时器还在自己跑，脉冲没断，舵机保持原位。
     * ────────────────────────────────────────────────────────────── */
    if (PS2_ReadData() == 0)
    {
        Mecanum_Stop();
        return;
    }
    d = PS2_GetData();

    /* ──────────────────────────────────────────────────────────────
     *  ①' 模式自愈：不在模拟模式就定期重试切回去
     *
     *      mode = 0x73 → 模拟模式，摇杆 0~255（本工程必须在这个模式）
     *      mode = 0x41 → 数字模式，摇杆字节恒为 0xFF
     *
     * 数字模式下摇杆字节是 0xFF，送进 Joy_Norm() 会被算成
     * "两个方向都推满"，所以下面的摇杆分支用 if (d.mode == 0x73)
     * 挡死了。按键在两种模式下都有效，所以调舵机不受影响。
     * ────────────────────────────────────────────────────────────── */
    if (d.mode != 0x73)
    {
        static uint32_t last_analog_try = 0u;

        /* 每 500ms 自动尝试一次切回模拟模式。
         * 限频的原因：一次重试要连发 4 帧，约 1ms，每 20ms 循环里
         * 都做会把 PS2 正常轮询挤掉。 */
        if ((HAL_GetTick() - last_analog_try) >= 500u)
        {
            last_analog_try = HAL_GetTick();
            (void)PS2_TryEnterAnalog();
        }
    }

    /* ──────────────────────────────────────────────────────────────
     *  ② 底盘：只认两个摇杆
     *
     *  左摇杆 → vx / vy（前后、左右平移，含 8 个方向）
     *  右摇杆 → w（只取左右，上下不管）
     *
     *  摇杆是模拟量，推 20% 就慢走，推到底才全速。
     *  这跟十字键那种"一按就是固定 60%"的开关量手感完全不同，
     *  也是判断"车到底是谁在开"的依据。
     * ────────────────────────────────────────────────────────────── */
    if (d.mode == 0x73)
    {
        JoyResult mv = Joystick_ReadMove(d.ljoy_x, d.ljoy_y);

        Joystick_ToVector(mv, &vx, &vy);
        w = Joystick_ReadRotate(d.rjoy_x);
    }

    /* ──────────────────────────────────────────────────────────────
     *  ②' L1 / R1 备用转向
     *
     *  为什么留着？右摇杆哪天进灰、漂了、或者干脆失灵，
     *  这两个键还能让车转起来，不至于当场报废。
     *
     *  为什么不占舵机的键？舵机用的是十字键 + △○×□，
     *  肩键不在那 8 个里面，借来用不冲突。
     *
     *  按了就以按键为准（覆盖摇杆的 w），因为按键是明确意图。
     * ────────────────────────────────────────────────────────────── */
    if (PS2_IS_PRESSED(d.btn2, PS2_BTN2_R1)) { w =  BTN_DRIVE_SPEED; }
    if (PS2_IS_PRESSED(d.btn2, PS2_BTN2_L1)) { w = -BTN_DRIVE_SPEED; }

    /* ──────────────────────────────────────────────────────────────
     *  ③ 下发电机
     *
     *  三个都是 0 → 停车。
     *  这里用滑停（Coast）而不是刹车：电机断电，车靠惯性慢慢停下，
     *  平稳、不伤齿轮、也不会让四个电机一直憋着电流。
     *  代价是车会继续滑一小段 —— 靠近方块要夹的时候，提前松手。
     * ────────────────────────────────────────────────────────────── */
    if (vx == 0 && vy == 0 && w == 0)
    {
        Mecanum_Stop();
    }
    else
    {
        /* 有输入 → 交给麦轮解算，它内部会做 5V 安全限幅 */
        Mecanum_Drive(vx, vy, w);
    }

    /* ──────────────────────────────────────────────────────────────
     *  ④ 机械臂：把两个按键字节交给 arm.c
     *
     *  为什么不和底盘一起判断？
     *    底盘看的是摇杆，机械臂看的是按键，两套输入互不相干。
     *    分开写，以后想给舵机加"存位/回位"，只动 arm.c，这里不看。
     *
     *  为什么放在最后？
     *    先让底盘这一拍的速度稳定下来，再动机械臂，
     *    舵机转动的抖动不会影响刚设定好的电机速度，整车更稳。
     * ────────────────────────────────────────────────────────────── */
    Arm_HandleKeys(d.btn1, d.btn2);
}
