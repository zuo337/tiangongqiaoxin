/**
 * ============================================================================
 *  ctrl.h —— 总调度（主循环里唯一需要认识的东西）
 * ============================================================================
 *
 *  分工：
 *    joystick.c  负责"摇杆在哪个区"
 *    mecanum.c   负责"四个轮子各转多快"
 *    arm.c       负责"哪个按键管哪个舵机"
 *    ctrl.c      负责"什么时候去问手柄、把结果交给谁"
 *
 *  你在 main.c 里只需要认识下面两个函数。
 * ============================================================================
 */
#ifndef __CTRL_H
#define __CTRL_H

#include <stdint.h>
#include "robot_conf.h"   /* 把 CTRL_PERIOD_MS 带进来，main.c 里要用它做延时 */

/* ---------------------------------------------------------------------------
 *  对外函数
 * ------------------------------------------------------------------------- */

/* 开机调一次：电机 + 舵机 + 手柄 全部初始化 */
void CTRL_Init(void);

/* 主循环里每 CTRL_PERIOD_MS 毫秒调一次：
 * 读手柄 → 驱动小车 → 驱动机械臂 */
void CTRL_Update(void);

#endif /* __CTRL_H */
