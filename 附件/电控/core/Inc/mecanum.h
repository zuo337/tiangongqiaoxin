/**
 * ============================================================================
 *  mecanum.h —— 麦克纳姆轮底盘（4 个电机 = 2 片 DRV8833）
 * ============================================================================
 *
 *  【它负责什么】
 *  你告诉它"我要怎么动"，它算出来"四个轮子各转多快"。
 *  至于"我要怎么动"是谁说的（手柄？还是自动驾驶？），它不关心。
 *
 *  【三个运动分量】
 *    vx 前后方向   （+ = 前进，- = 后退）
 *    vy 左右方向   （+ = 右移，- = 左移）
 *    w  原地旋转   （+ = 顺时针，- = 逆时针）
 *
 *  【硬件】
 *    左前 = PA0/PA1 (TIM2_CH1/2)     右前 = PA6/PA7 (TIM3_CH1/2)
 *    左后 = PA2/PA3 (TIM2_CH3/4)     右后 = PB0/PB1 (TIM3_CH3/4)
 *    TIM2/TIM3 都是 20kHz（预分频 0、周期 3599），超出人耳听觉，不会吱吱叫。
 * ============================================================================
 */
#ifndef __MECANUM_H
#define __MECANUM_H

#include <stdint.h>
#include "drv8833.h"        /* 用到 MotorID 和 DRV8833_Forward / Backward / Coast */
#include "robot_conf.h"    /* 用到 MOTOR_MAX_DUTY / MOTOR_MIN_DUTY */

/**
 * 输入分量的范围：-100 ~ +100
 * 100 表示"这个方向推满了"。
 */
#define MEC_INPUT_MAX   100

/* ---------------------------------------------------------------------------
 *  对外函数
 * ------------------------------------------------------------------------- */

/* 按三个分量驱动小车。vx 前后 / vy 平移 / w 旋转 */
void Mecanum_Drive(int16_t vx, int16_t vy, int16_t w);

/* 停车。用"滑行"方式：四个电机断电，靠惯性慢慢停下 */
void Mecanum_Stop(void);

#endif /* __MECANUM_H */
