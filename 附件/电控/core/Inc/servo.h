/**
 * ============================================================================
 *  servo.h —— 四路舵机驱动（3 个大舵机 + 1 个小舵机）
 * ============================================================================
 *
 *  【舵机怎么控制】
 *  舵机不看电压大小，只看"高电平持续了多久"，学名叫 PWM 脉宽。
 *  每 20ms 必须来一个脉冲，脉冲里的高电平宽度决定转到哪：
 *
 *        ~500us = 0 度     1500us = 90 度     ~2500us = 180 度
 *
 *  注意：这里刻意没写"500us 就是 0 度"。500 和 2500 只是手册标称的
 *  理论极值，真机每颗都略有差异，装机构后还会被机械限位卡住。
 *  实际能用多少，必须自己标（见 robot_conf.h 里的标定说明）。
 *
 *  【本工程的实际接线】
 *
 *    逻辑编号   机械名称    引脚    定时器通道     PCB 印字
 *    ----------------------------------------------------------
 *      1       大舵机1     PB6     TIM4_CH1         1
 *      2       大舵机2     PB7     TIM4_CH2         2
 *      3       大舵机3     PB8     TIM4_CH3         3
 *      6       小舵机6     PA11    TIM1_CH4         6
 *
 *  !!! 编号只做 ID，绝不当数组下标 !!!
 *
 *    内部数组只有 4 个槽（下标 0~3）。编号 6 如果直接拿来当下标，
 *    就是 pos[6] —— 越过数组末尾，写坏旁边的变量。
 *    这种错【不会报编译错误】，现象是"别的变量莫名其妙变了"，
 *    能让你查一整天。所以所有对外接口都传"逻辑编号"，内部用
 *    find_slot() 查表换算成 0~3 的槽位。
 *
 *  【定时器参数】（tim.c 里已经配好，本模块一个字都不用改）
 *
 *    PSC = 71    → 72MHz ÷ (71+1) = 1MHz，1 个计数 = 1 微秒
 *    ARR = 19999 → 20000 × 1us = 20ms = 50Hz
 *
 *    这个配置有个特别好用的副作用：CCR 里填的数值，数值上就等于
 *    脉宽的微秒数。填 1500 就是 1.5ms，不用算任何占空比百分比。
 *
 *  【空着的两路】
 *    PB9 (TIM4_CH4) 和 PA8 (TIM1_CH1) 在 CubeMX 里配了 PWM，但
 *    本模块不启动它们。配了不启动是无害的，只是引脚上不出波形。
 * ============================================================================
 */
#ifndef __SERVO_H
#define __SERVO_H

#include <stdint.h>
#include "robot_conf.h"

/* ---------------------------------------------------------------------------
 *  舵机逻辑编号（必须和 PCB 上的印字一致）
 *  想加第五路：这里加一个编号 + servo.c 表里加一行，别的不用动。
 * ------------------------------------------------------------------------- */
#define SERVO_ID_BIG1     1u   /* 大舵机1  PB6   TIM4_CH1 */
#define SERVO_ID_BIG2     2u   /* 大舵机2  PB7   TIM4_CH2 */
#define SERVO_ID_BIG3     3u   /* 大舵机3  PB8   TIM4_CH3 */
#define SERVO_ID_SMALL6   6u   /* 小舵机6  PA11  TIM1_CH4 */

#define SERVO_COUNT       4u   /* 一共 4 路（数组长度，不是最大编号！） */


/* ---------------------------------------------------------------------------
 *  对外函数
 * ------------------------------------------------------------------------- */

/**
 * 开机调一次。
 * 先把四路 CCR 都写成 SERVO_INIT_US（中位），再启动 PWM。
 *
 * 顺序不能反：先启动再改 CCR 的话，上电瞬间会先输出 tim.c 里
 * CubeMX 存的初值，舵机会先"啪"地甩一下再回中位。
 */
void     Servo_Init(void);

/**
 * 把 id 号舵机直接推到 pulse_us 这个脉宽（微秒）。
 *
 * 会自动钳在 [min_us, max_us] 之内，传超范围的值不会真的打出去。
 * 标定阶段就是靠这个函数一点一点试边界的。
 *
 * @param id       逻辑编号（1/2/3/6），不是数组下标
 * @param pulse_us 目标脉宽，单位微秒（典型 700~2300）
 */
void     Servo_SetPulse(uint8_t id, uint16_t pulse_us);

/**
 * 问 id 号舵机现在记着的脉宽是多少微秒。
 *
 * 注意：这是【软件记账】，不是实测。舵机被卡住没转到位，
 * 这个数照样会变。普通舵机没有位置反馈，别指望它说真话。
 */
uint16_t Servo_GetPulse(uint8_t id);

/**
 * 让 id 号舵机朝 dir 方向挪一步（SERVO_STEP_US 微秒）。
 *
 * dir > 0 → 脉宽变大（一个方向）
 * dir < 0 → 脉宽变小（反方向）
 *
 * 哪边是顺时针取决于舵机怎么装的，装反了就把 arm.c 表里的
 * +1 / -1 对调，不要来这里改符号。
 */
void     Servo_Step(uint8_t id, int8_t dir);

#endif /* __SERVO_H */
