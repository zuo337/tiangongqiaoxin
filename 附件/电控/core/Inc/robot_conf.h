/**
 * ============================================================================
 *  robot_conf.h —— 所有能调的数字都放这一个文件
 * ============================================================================
 *
 *  为什么要单独一个文件？
 *    这样你调车的时候只开这一个文件，不用在五六个文件里翻。
 *    改完保存，其它 .c 文件一个字都不用动。
 *
 *  【文件名后缀 .h】
 *    h = header（头文件）。它里面只有 #define 和声明，没有真正的代码。
 *    每个用到这些参数的 .c 文件都 #include 它，就能拿到同一份配置。
 * ============================================================================
 */
#ifndef __ROBOT_CONF_H
#define __ROBOT_CONF_H

#include <stdint.h>

/* ==========================================================================
 *  一、电机：5V 供电下的安全转速
 * ========================================================================== */

/**
 * 电机电源电压，单位毫伏(mV)。用 5V 供电就填 5000。
 * 注意：这是 DRV8833 上 VM 引脚的电压，不是芯片的 3.3V 逻辑电。
 */
#define MOTOR_VSUPPLY_MV    5000

/**
 * 电机额定电压，单位毫伏(mV)。看你电机铭牌。
 * 常见 6V 减速电机(TT马达/N20)填 6000；3V 的小电机填 3000。
 */
#define MOTOR_VRATED_MV     6000


/* ── 下面这个 90 是怎么来的 ──────────────────────────────────────────────
 *
 *  第 1 步：算电机能承受的最高电压
 *          6V 额定 × 90%（留 10% 余量）= 5.4V
 *          你的电源只有 5V，比 5.4V 还低，所以【电压上是安全的】。
 *
 *  第 2 步：但电压安全 ≠ 电流安全
 *          电机刚启动或堵住不转时，电流会冲到额定好几倍，
 *          DRV8833 持续电流上限 1.5A（峰值 2A），超了芯片会烫手甚至保护断电。
 *          所以再压 10%，把最大占空比定在 90%。
 *
 *  第 3 步：占空比 = 加在电机上的平均电压 / 电源电压
 *          90% × 5V = 4.5V 平均电压，电机在这个范围内长期跑不会过热。
 *
 *  ── 如果你的电机不一样，自己重算 ──
 *  例：3V 额定电机 + 5V 供电
 *      3V × 90% = 2.7V  →  2.7V / 5V = 54%  →  最大占空比填 54
 *      千万别填 100，否则 5V 直接灌进 3V 电机，几秒钟就烧。
 * ──────────────────────────────────────────────────────────────────────── */
#define MOTOR_MAX_DUTY      90


/**
 * 最小占空比：比这个值还小就直接当成 0（滑行）。
 *
 * 为什么需要它？
 *   占空比很低时（比如 10%），电机转子根本推不动，只会：
 *     - 嗡嗡响但转不起来
 *     - 电流全变成热量，电机和驱动芯片都发烫
 *     - 齿轮箱咬着劲，机械臂在那抖
 *   四个轮子如果有的转有的不转，车还会扭着走。
 *   所以算出来比这还小的话，不如干脆不给电，让它自由滑行。
 *
 * 电机轻好启动 → 改到 15；电机沉、带减速箱 → 改到 25~30。
 */
#define MOTOR_MIN_DUTY      20


/* ==========================================================================
 *  二、摇杆分区
 * ========================================================================== */

/**
 * 摇杆死区（0~100）。
 * 20 表示：离中心 20% 以内都当成"手没碰"。
 * 换算成原始值大约是 128 ± 25，也就是 103~153 之间都算中间。
 *
 * 车自己会慢慢爬 → 调大（25~30）
 * 觉得推了不跟手   → 调小（12~15）
 */
#define JOY_DEADZONE        20

/**
 * 是否启用 45° 斜向运动。
 *   1 = 左摇杆分 8 个区（前后左右 + 四个斜角）
 *   0 = 只分 4 个区（前后左右），斜着推会自动归到最近的正方向
 * 比赛要斜着走就保持 1，怕操作失误就改 0。
 */
#define JOY_USE_DIAGONAL    1


/* ==========================================================================
 *  三、机械臂舵机
 * ==========================================================================
 *
 *  【为什么不按角度配，而按脉宽微秒配】
 *
 *  按角度的话，中间要做一次 angle × 2000 / 180 的整数除法，
 *  取整会带来误差，而且 1 度 ≈ 11 微秒，比舵机自己的分辨率还粗。
 *  直接存微秒数就没有这层换算：写多少就是多少，也方便你标定
 *  的时候"每次加 20 微秒"这样一点一点试。
 *
 *  别担心看不懂微秒：定时器配的是 1MHz 计数，所以
 *  CCR 里填的那个数，数值上就是微秒数，一一对应。
 * ------------------------------------------------------------------------ */

/* ── 3.1 每路舵机的脉宽安全边界（微秒）────────────────────────────────
 *
 *  下面这四组默认值（700 / 2300）【不是】从舵机手册抄的，
 *  是刻意留了余量的保守起点：
 *      1500us = 中位 90 度
 *      700 ~ 2300 ≈ 中位 ±72 度，行程约 108 度
 *
 *  为什么不用手册上的 500 / 2500？
 *    因为 500 和 2500 是"理论极值"，真机每颗都略有差异，
 *    装机构之后还会被机械限位卡住。一上来就给极值，
 *    舵机会顶到死点持续堵转 —— MG996R 堵转 2.5A，
 *    三个一起 7.5A，电源直接崩，单片机跟着复位。
 *
 *  ★ 必须自己标定，四路分别标，不能共用一套 ★
 *
 *    标定步骤（装机构之前、空载做，做完就没法重来了）：
 *      1. 从上电的 1500 出发，每次 ±20 微秒，朝一个方向慢慢推；
 *      2. 听到齿轮"咔"一声、或者声音明显变大、或者它停住不动
 *         → 立刻退回 20 微秒；
 *      3. 这个"刚好不响"的值，就是这一头的边界，填到下面；
 *      4. 反方向同样做一遍；
 *      5. 四组数抄到纸上或记进笔记。丢了要重标，很费时间。
 *
 *    标完之后，把下面四组值改小范围，舵机就再也不会顶死。
 */
#define SERVO_BIG1_MIN_US     700u      /* 大舵机1  PB6  下限 */
#define SERVO_BIG1_MAX_US    2300u      /* 大舵机1  PB6  上限 */

#define SERVO_BIG2_MIN_US     700u      /* 大舵机2  PB7  下限 */
#define SERVO_BIG2_MAX_US    2300u      /* 大舵机2  PB7  上限 */

#define SERVO_BIG3_MIN_US     700u      /* 大舵机3  PB8  下限 */
#define SERVO_BIG3_MAX_US    2300u      /* 大舵机3  PB8  上限 */

#define SERVO_SMALL6_MIN_US   700u      /* 小舵机6  PA11 下限 */
#define SERVO_SMALL6_MAX_US  2300u      /* 小舵机6  PA11 上限 */


/* ── 3.2 上电初始位置（微秒）─────────────────────────────────────────
 *
 *  1500 = 中位。四路都回中位。
 *
 *  ⚠ 装好机构之后要留意：如果某个关节在中位会撞到别的东西，
 *    就把这一路单独改到你想要的"安全位"（需要改 servo.c 里
 *    表最后一列，不是改这个宏）。上电瞬间四路一起甩到 1500，
 *    是新手最容易忽略的一次事故。
 */
#define SERVO_INIT_US        1500u


/* ── 3.3 每按一拍走多少微秒 ─────────────────────────────────────────
 *
 *  主循环 20ms 一次，所以每按一拍走 SERVO_STEP_US 微秒：
 *      20us/步 × 50 步/秒 = 1000us/秒
 *      走完 700~2300 全行程（1600us）大约 1.6 秒
 *      20us 大约对应 1.8 度，肉眼看起来是连续转动的
 *
 *  调参方向：
 *      觉得太糙、想更细腻 → 改 10（走完全程 3.2 秒）
 *      觉得太慢、想快点   → 改 40（走完全程 0.8 秒，但容易冲过头）
 *
 *  ⚠ 不要小于 10。舵机死区大概 5 微秒，步长太小会出现
 *    "按了三四下它才动一下"，你会以为代码坏了。
 */
#define SERVO_STEP_US          20u


/* ==========================================================================
 *  四、主循环节奏
 * ========================================================================== */

/**
 * 主循环每隔多少毫秒跑一次。
 * 20ms = 每秒 50 次，对手柄来说足够跟手了。
 */
#define CTRL_PERIOD_MS      20

#endif /* __ROBOT_CONF_H */
