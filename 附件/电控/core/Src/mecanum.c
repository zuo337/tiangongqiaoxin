/**
 * ============================================================================
 *  mecanum.c —— 麦克纳姆轮底盘（4 个电机 = 2 片 DRV8833）
 *
 *  整个文件就三步：
 *    ① 套公式算出四个轮子的速度
 *    ② 归一化（防止某个轮子算出来超限）
 *    ③ 下发到电机，顺手做 5V 安全限幅
 * ============================================================================
 */
#include "mecanum.h"

/* ==========================================================================
 *  内部函数：给单个轮子设定带符号的速度
 *  spd > 0 正转，spd < 0 反转，spd = 0 滑行
 * ========================================================================== */
static void Motor_SetSigned(MotorID id, int16_t spd)
{
    int16_t abs;

    /* 先取绝对值。取完就只处理正数，后面逻辑简单很多 */
    abs = (spd >= 0) ? spd : (int16_t)(-spd);

    /* ── 5V 安全限幅第 1 关：下限 ──
     * 占空比太小的话电机推不动负载，只会嗡嗡响、发热、不转。
     * 与其让它白耗电还发烫，不如直接断电让它滑行。
     */
    if (abs < MOTOR_MIN_DUTY)
    {
        DRV8833_Coast(id);
        return;
    }

    /* ── 5V 安全限幅第 2 关：上限 ──
     * 超过 MOTOR_MAX_DUTY（默认 90）就砍到 90，
     * 这样加在电机上的平均电压不会超过 4.5V，长期跑不会过热。
     */
    if (abs > MOTOR_MAX_DUTY) abs = MOTOR_MAX_DUTY;

    /* 按符号决定正转还是反转 */
    if (spd > 0)      DRV8833_Forward(id,  (uint8_t)abs);
    else              DRV8833_Backward(id, (uint8_t)abs);
}


/* ==========================================================================
 *  对外：驱动小车
 * ========================================================================== */
void Mecanum_Drive(int16_t vx, int16_t vy, int16_t w)
{
    int32_t lf, rf, lb, rb;     /* 用 32 位，中间结果不会溢出 */
    int32_t maxv;

    /* ---------------------------------------------------------------
     * 第 0 步：输入限幅
     * 万一上层传进来 200，先压回 ±100，避免后面全乱套
     * --------------------------------------------------------------- */
    if (vx >  MEC_INPUT_MAX) vx =  MEC_INPUT_MAX;
    if (vx < -MEC_INPUT_MAX) vx = -MEC_INPUT_MAX;
    if (vy >  MEC_INPUT_MAX) vy =  MEC_INPUT_MAX;
    if (vy < -MEC_INPUT_MAX) vy = -MEC_INPUT_MAX;
    if (w  >  MEC_INPUT_MAX) w  =  MEC_INPUT_MAX;
    if (w  < -MEC_INPUT_MAX) w  = -MEC_INPUT_MAX;

    /* ---------------------------------------------------------------
     * 第 0.5 步：把输入整体压到 5V 安全范围
     *
     * 这一步很关键，原因有两个：
     *
     * ① 让满推 = 安全上限
     *    输入 100 被压成 MOTOR_MAX_DUTY（默认 90），
     *    摇杆整个行程 0~100 就线性对应到占空比 0~90，不留死行程。
     *
     * ② 保护四个轮子的【速度比例】
     *    如果不在这里压，而是等算出 100 之后再逐个砍到 90，就会出事：
     *      比如算出来 左前=100 右前=50（2:1），
     *      逐个砍 → 左前=90 右前=50（变成 1.8:1），
     *      比例一乱，车就不走直线了，会往一边偏。
     *    先整体缩放输入，后面的归一化就能按比例处理，方向始终准确。
     * --------------------------------------------------------------- */
    vx = (int16_t)((int32_t)vx * MOTOR_MAX_DUTY / MEC_INPUT_MAX);
    vy = (int16_t)((int32_t)vy * MOTOR_MAX_DUTY / MEC_INPUT_MAX);
    w  = (int16_t)((int32_t)w  * MOTOR_MAX_DUTY / MEC_INPUT_MAX);

    /* ---------------------------------------------------------------
     * 第 1 步：套麦轮公式
     *
     *   左前 = vx + vy + w
     *   右前 = vx - vy - w
     *   左后 = vx - vy + w
     *   右后 = vx + vy - w
     *
     * 这套公式和你 car.c 里那张离散动作表是完全对齐的，验一下：
     *   前进   vx=+100          → 四轮都是 +100        ✔ 和 Car_Forward 一致
     *   右平移 vy=+100          → 左前+100 右前-100 左后-100 右后+100
     *                             ✔ 和 Car_SlideRight 一致
     *   顺时针 w=+100           → 左前+100 右前-100 左后+100 右后-100
     *                             ✔ 和 Car_RotateCW 一致
     * --------------------------------------------------------------- */
    lf = vx + vy + w;
    rf = vx - vy - w;
    lb = vx - vy + w;
    rb = vx + vy - w;

    /* ---------------------------------------------------------------
     * 第 2 步：归一化
     *
     * 为什么要这一步？
     *   三个方向同时推满时（vx=vy=w=100），左前会算到 300。
     *   如果不处理直接砍到 100，四个轮子的比例就乱了，车会跑偏。
     *   所以先找出最大那个，再【整体】按比例缩小，
     *   这样四个轮子的相对关系不变，方向才准确。
     *
     * maxv 初值给 1 而不是 0，是为了下面除法不会出现"除以 0"。
     * --------------------------------------------------------------- */
    maxv = 1;
    if (lf >  maxv) maxv =  lf;
    if (lf < -maxv) maxv = -lf;
    if (rf >  maxv) maxv =  rf;
    if (rf < -maxv) maxv = -rf;
    if (lb >  maxv) maxv =  lb;
    if (lb < -maxv) maxv = -lb;
    if (rb >  maxv) maxv =  rb;
    if (rb < -maxv) maxv = -rb;

    /* 注意这里压到的是 MOTOR_MAX_DUTY（默认 90），不是 100。
     * 因为输入已经缩放过了，轮子的上限本来就是 90。*/
    if (maxv > MOTOR_MAX_DUTY)
    {
        lf = lf * MOTOR_MAX_DUTY / maxv;
        rf = rf * MOTOR_MAX_DUTY / maxv;
        lb = lb * MOTOR_MAX_DUTY / maxv;
        rb = rb * MOTOR_MAX_DUTY / maxv;
    }

    /* ---------------------------------------------------------------
     * 第 3 步：下发给四个电机
     * 真正的安全限幅（上限 90 / 下限 20）在 Motor_SetSigned 里面做
     * --------------------------------------------------------------- */
    Motor_SetSigned(MOTOR_LF, (int16_t)lf);
    Motor_SetSigned(MOTOR_RF, (int16_t)rf);
    Motor_SetSigned(MOTOR_LB, (int16_t)lb);
    Motor_SetSigned(MOTOR_RB, (int16_t)rb);
}


/* ==========================================================================
 *  对外：停车
 *
 *  这里用 Coast（滑行）而不是 Brake（刹车）：
 *    Coast = 两个控制脚都给 0，电机断电，车靠惯性慢慢滑停 —— 平稳、省电
 *    Brake = 两个控制脚都给 1，电机被短路，会产生阻力急停 —— 快但伤齿轮
 *  手柄松开时用滑停手感更好，也不会让四个电机一直憋着电流。
 * ------------------------------------------------------------------------- */
void Mecanum_Stop(void)
{
    DRV8833_Coast(MOTOR_LF);
    DRV8833_Coast(MOTOR_RF);
    DRV8833_Coast(MOTOR_LB);
    DRV8833_Coast(MOTOR_RB);
}
